"""Interactive Streamlit dashboard for the customer segmentation project."""

from pathlib import Path

import pandas as pd
import plotly.express as px
import streamlit as st


# Set the page layout before drawing any dashboard components.
st.set_page_config(page_title="Customer Insights", page_icon="📊", layout="wide")

# Add light visual styling to make the summary cards easy to scan.
st.markdown(
    """
    <style>
        .block-container {padding-top: 1.5rem; padding-bottom: 2rem;}
        [data-testid="stMetric"] {
            background: #f4f7fb;
            border: 1px solid #e4eaf2;
            padding: 16px;
            border-radius: 12px;
        }
        h1 {color: #183153;}
    </style>
    """,
    unsafe_allow_html=True,
)

st.title("📊 Telecom Customer Insights")
st.caption("Customer segments, service patterns, and churn")

# Load the CSV generated by customer_segmentation.py. Stop with a clear message
# if the analysis has not yet been run or its output is in a different folder.
PROJECT_DIR = Path(__file__).resolve().parent
SEGMENTED_FILE = PROJECT_DIR / "telco_customers_with_segments.csv"
try:
    df = pd.read_csv(SEGMENTED_FILE)
except FileNotFoundError:
    st.error(
        "Could not find telco_customers_with_segments.csv. "
        "Run customer_segmentation.py first."
    )
    st.stop()

# Prepare fields used for display and calculations.
df["Segment"] = df["Segment"].astype(int)
df["Churned"] = df["Churn"].eq("Yes")

# Give dashboard readers interactive filters for segment, churn, contract, and
# internet service. Start with every available option selected.
st.sidebar.title("Dashboard filters")
all_segments = sorted(df["Segment"].unique().tolist())
selected_segments = st.sidebar.multiselect(
    "Customer segment",
    options=all_segments,
    default=all_segments,
    format_func=lambda value: f"Segment {value}",
)

churn_options = sorted(df["Churn"].dropna().unique().tolist())
selected_churn = st.sidebar.multiselect(
    "Churn status", options=churn_options, default=churn_options
)

contract_options = sorted(df["Contract"].dropna().unique().tolist())
selected_contracts = st.sidebar.multiselect(
    "Contract type", options=contract_options, default=contract_options
)

internet_options = sorted(df["InternetService"].dropna().unique().tolist())
selected_internet = st.sidebar.multiselect(
    "Internet service", options=internet_options, default=internet_options
)

# Keep only rows matching every selected filter.
filtered = df[
    df["Segment"].isin(selected_segments)
    & df["Churn"].isin(selected_churn)
    & df["Contract"].isin(selected_contracts)
    & df["InternetService"].isin(selected_internet)
].copy()

# Explain why no charts are shown if filter selections exclude every customer.
if filtered.empty:
    st.warning("No customers match those filters. Select more options in the sidebar.")
    st.stop()

# Calculate key metrics from the filtered customers and display them in cards.
customers = len(filtered)
average_charge = filtered["MonthlyCharges"].mean()
churn_rate = filtered["Churned"].mean() * 100
average_tenure = filtered["tenure"].mean()

card1, card2, card3, card4 = st.columns(4)
card1.metric("Customers", f"{customers:,}")
card2.metric("Avg. monthly charge", f"{average_charge:.2f}")
card3.metric("Churn rate", f"{churn_rate:.1f}%")
card4.metric("Avg. tenure", f"{average_tenure:.1f} months")

# Organize the dashboard into three tabs so users can explore the summary,
# segment behavior, and individual customer rows without crowding one page.
overview_tab, segment_tab, customer_tab = st.tabs(
    ["📈 Overview", "👥 Segment explorer", "📋 Customer records"]
)

with overview_tab:
    left, right = st.columns(2)

    # Count customers in each segment for the first overview chart.
    segment_sizes = (
        filtered["Segment"].value_counts().sort_index().rename_axis("Segment")
        .reset_index(name="Customers")
    )
    with left:
        fig = px.bar(
            segment_sizes,
            x="Segment",
            y="Customers",
            color="Segment",
            title="Customers in each segment",
            color_discrete_sequence=["#3977c3", "#36a89a", "#f0a44b"],
        )
        fig.update_layout(showlegend=False)
        st.plotly_chart(fig, width="stretch")

    # Calculate a small profile table for later charts and the segment explorer.
    segment_summary = (
        filtered.groupby("Segment", as_index=False)
        .agg(
            Customers=("customerID", "count"),
            Churn_rate=("Churned", "mean"),
            Avg_monthly_charge=("MonthlyCharges", "mean"),
            Avg_tenure=("tenure", "mean"),
        )
    )
    segment_summary["Churn_rate"] *= 100

    # Compare churn percentages across the segments.
    with right:
        fig = px.bar(
            segment_summary,
            x="Segment",
            y="Churn_rate",
            color="Segment",
            title="Churn rate by segment",
            labels={"Churn_rate": "Churn rate (%)"},
            color_discrete_sequence=["#3977c3", "#36a89a", "#f0a44b"],
        )
        fig.update_layout(showlegend=False)
        st.plotly_chart(fig, width="stretch")

    left, right = st.columns(2)

    # Show how monthly charges are distributed across the customer segments.
    with left:
        fig = px.histogram(
            filtered,
            x="MonthlyCharges",
            color="Segment",
            nbins=25,
            title="Monthly charge distribution",
            labels={"MonthlyCharges": "Monthly charges"},
            color_discrete_sequence=["#3977c3", "#36a89a", "#f0a44b"],
        )
        st.plotly_chart(fig, width="stretch")

    # Compare contract choices across segments using grouped bars.
    with right:
        fig = px.histogram(
            filtered,
            x="Contract",
            color="Segment",
            barmode="group",
            title="Contract types by segment",
            color_discrete_sequence=["#3977c3", "#36a89a", "#f0a44b"],
        )
        st.plotly_chart(fig, width="stretch")

with segment_tab:
    st.subheader("Explore customer behavior")

    # Use a scatter plot to compare tenure and monthly charges. Hovering over a
    # point reveals the customer ID and selected service/contract details.
    plot_df = filtered.copy()
    plot_df["Segment"] = plot_df["Segment"].astype(str)
    fig = px.scatter(
        plot_df,
        x="tenure",
        y="MonthlyCharges",
        color="Segment",
        symbol="Churn",
        hover_data=["customerID", "Contract", "InternetService", "TechSupport", "Churn"],
        title="Tenure and monthly charges",
        labels={
            "tenure": "Tenure (months)",
            "MonthlyCharges": "Monthly charges",
            "Segment": "Customer segment",
        },
        color_discrete_sequence=["#3977c3", "#36a89a", "#f0a44b"],
    )
    st.plotly_chart(fig, width="stretch")

    # Show segment-level metrics in a compact table.
    st.subheader("Segment profile")
    st.dataframe(segment_summary.round(1), hide_index=True, width="stretch")

with customer_tab:
    st.subheader("Filtered customer records")

    # Limit the table to useful identifying, behavioral, and outcome columns.
    columns_to_show = [
        "customerID", "Segment", "tenure", "MonthlyCharges",
        "InternetService", "Contract", "TechSupport", "Churn",
    ]
    st.dataframe(filtered[columns_to_show], hide_index=True, width="stretch")

    # Let users export the filtered table for additional analysis.
    st.download_button(
        "Download filtered customer data",
        data=filtered.to_csv(index=False).encode("utf-8"),
        file_name="filtered_customer_segments.csv",
        mime="text/csv",
    )
